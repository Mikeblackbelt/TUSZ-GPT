"""
Label category constants and classification functions for EEG window datasets.
"""

from __future__ import annotations

from typing import Any, Optional
import numpy as np
import pandas as pd

# Label category constants
LABEL_CATEGORY_BACKGROUND = "background"
LABEL_CATEGORY_PREICTAL = "preictal"
LABEL_CATEGORY_ICTAL = "ictal"
LABEL_CATEGORY_EXCLUDED = "excluded"

ALLOWED_LABEL_CATEGORIES = {
    LABEL_CATEGORY_BACKGROUND,
    LABEL_CATEGORY_PREICTAL,
    LABEL_CATEGORY_ICTAL,
    LABEL_CATEGORY_EXCLUDED,
}

# Known base seizure types from TUH EEG dataset (TUSZ) / preictal preprocessing engine
KNOWN_SEIZURE_TYPES = {
    "fnsz", "gnsz", "cpsz", "spsz", "tnsz", "tcsz", "absz", "mysz", "cnsz", "atsz", "seiz", "sz", "nesz"
}

# Background raw labels emitted by preprocessing or raw CSVs
BACKGROUND_LABELS = {
    "bg", "bckg", "background", "0", "0.0", "-1", "none", "nan", "null", ""
}

# Artifact / exclusion tags
EXCLUSION_TAGS = {
    "artf", "eyem", "eybl", "chew", "cero", "eloh", "elec", "gspd", "pled", "spsw", "gped"
}


def _suffix_starts_with_known_type(suffix: str) -> bool:
    """Return True if *suffix* starts with any entry in KNOWN_SEIZURE_TYPES.

    This handles compound labels generated by the preprocessing pipeline:
      - Consecutive labels: ``cgnszfnsz`` (two types concatenated)
      - Same-type doubles:  ``cgnsz2``
      - SOP-buffer labels:  ``pgnsz_sopbuffer``
    """
    return any(suffix.startswith(t) for t in KNOWN_SEIZURE_TYPES)


def classify_label(raw_val: Any) -> str:
    """Classify raw annotation label into one of four explicit categories:
    {'background', 'preictal', 'ictal', 'excluded'}.

    Handles compound labels emitted by the preprocessing pipeline:
      - ``c{type1}{type2}`` / ``c{type}2`` → consecutive → excluded
      - ``p{type}_sopbuffer`` → SOP-buffer preictal → excluded

    Raises ValueError if raw_val is unrecognized (fail-loud).
    """
    if raw_val is None or (isinstance(raw_val, float) and np.isnan(raw_val)):
        return LABEL_CATEGORY_BACKGROUND

    s = str(raw_val).strip().lower()

    # 1. Exact background match
    if s in BACKGROUND_LABELS or s.startswith("0"):
        return LABEL_CATEGORY_BACKGROUND

    # 2. Exact ictal match
    if s in KNOWN_SEIZURE_TYPES:
        return LABEL_CATEGORY_ICTAL

    # 3. Preictal variants: 'p' + known seizure type
    if s in ("p", "preictal"):
        return LABEL_CATEGORY_PREICTAL
    if s.startswith("p") or s.startswith("p_"):
        suffix = s[2:] if s.startswith("p_") else s[1:]
        # Exact preictal (e.g. "pgnsz")
        if suffix in KNOWN_SEIZURE_TYPES or not suffix:
            return LABEL_CATEGORY_PREICTAL
        # SOP-buffer preictal (e.g. "pgnsz_sopbuffer") → excluded
        if "_sopbuffer" in suffix and _suffix_starts_with_known_type(suffix.split("_")[0]):
            return LABEL_CATEGORY_EXCLUDED

    # 4. Excluded / Postictal / Continuing / Artifact variants
    if s in ("x", "q", "c", "postictal", "continuing", "exclusion") or s in EXCLUSION_TAGS:
        return LABEL_CATEGORY_EXCLUDED
    if s.startswith("q") or s.startswith("q_") or s.startswith("c") or s.startswith("c_") or s.startswith("x") or s.startswith("x_"):
        suffix = s[2:] if (s.startswith("q_") or s.startswith("c_") or s.startswith("x_")) else s[1:]
        # Accept exact match, empty suffix, OR compound suffixes (e.g. "gnszfnsz", "gnsz2")
        if not suffix or suffix in KNOWN_SEIZURE_TYPES or _suffix_starts_with_known_type(suffix):
            return LABEL_CATEGORY_EXCLUDED

    # 5. Fail-loud on anything unrecognized
    raise ValueError(
        f"Unrecognized dataset label '{raw_val}' (normalized: '{s}'). "
        f"Label must be explicitly allow-listed into one of {{background, preictal, ictal, excluded}}."
    )


SEIZURE_TYPE_CLASSES = sorted(KNOWN_SEIZURE_TYPES)

# Coarser seizure-type targets for the TYPE head. TUSZ's rare types (absz, tnsz,
# tcsz, cpsz, spsz, mysz, atsz, cnsz) have a handful of seizures each in a
# patient-disjoint split -- far below what a 13-way head can learn -- and they
# collapse onto fnsz/gnsz. The clinically standard coarse split is
# focal vs generalized. Types not listed in a grouping map to -1 (excluded
# from the type loss and metrics; the row is still an ictal row for occurrence).
TYPE_GROUPINGS = {
    "none": None,
    "focal_generalized": {
        "focal": ["fnsz", "cpsz", "spsz"],
        "generalized": ["gnsz", "absz", "tnsz", "tcsz", "mysz", "atsz", "cnsz"],
    },
    "fnsz_gnsz_other": {
        "fnsz": ["fnsz"],
        "gnsz": ["gnsz"],
        "other": ["cpsz", "spsz", "absz", "tnsz", "tcsz", "mysz", "atsz", "cnsz"],
    },
}


def extract_seizure_type(raw_val: Any) -> str:
    """Extract the base seizure subtype (e.g. 'gnsz') from a raw annotation label.

    This is distinct from `classify_label`: `classify_label` answers "is this
    window background/preictal/ictal/excluded", while this answers "which of
    the KNOWN_SEIZURE_TYPES does the associated seizure belong to". Used to
    build a genuine multi-class type target that is independent of the binary
    occurrence/preictal flag -- see the "type vs occurrence" note in dataset.py.

    Returns LABEL_CATEGORY_BACKGROUND (used here as a sentinel, not a real
    type) when no seizure type can be determined, e.g. for background windows
    or a bare "p"/"preictal" label with no encoded subtype.
    """
    if raw_val is None or (isinstance(raw_val, float) and np.isnan(raw_val)):
        return LABEL_CATEGORY_BACKGROUND

    s = str(raw_val).strip().lower()
    cat = classify_label(raw_val)

    if cat == LABEL_CATEGORY_BACKGROUND or cat == LABEL_CATEGORY_EXCLUDED:
        return LABEL_CATEGORY_BACKGROUND

    if cat == LABEL_CATEGORY_ICTAL:
        return s if s in KNOWN_SEIZURE_TYPES else LABEL_CATEGORY_BACKGROUND

    if cat == LABEL_CATEGORY_PREICTAL:
        if s in ("p", "preictal"):
            return LABEL_CATEGORY_BACKGROUND
        suffix = s[2:] if s.startswith("p_") else s[1:]
        return suffix if suffix in KNOWN_SEIZURE_TYPES else LABEL_CATEGORY_BACKGROUND

    return LABEL_CATEGORY_BACKGROUND


def _is_background_label(raw_val: Any) -> bool:
    """Return True if raw_val represents a background / non-seizure window."""
    return classify_label(raw_val) == LABEL_CATEGORY_BACKGROUND


def _is_sopbuffer_label(raw_val: Any) -> bool:
    """True for the SOP-buffer rows the preprocessing pipeline emits between a
    preictal window and seizure onset (e.g. ``pgnsz_sopbuffer``)."""
    return "_sopbuffer" in str(raw_val).strip().lower()


def _build_valid_ictal_mask(
    df: pd.DataFrame,
    label_col: str,
    start_col: str,
    channel_col: Optional[str] = "channel",
) -> pd.Series:
    """Return a boolean Series (same index as *df*) that is **False** for any
    ictal row that is NOT preceded by a valid preictal lead-in.

    Non-ictal rows (background, preictal, postictal, continuing, exclusion)
    are always True — they are handled by separate filters.

    Rules enforced (per session, sorted by start_time):
    * The nearest preceding NON-ictal row -- skipping over ``p*_sopbuffer``
      rows, which the preprocessing pipeline always places between the
      preictal window and onset -- must be a preictal (``p*``) row.
    * Contiguous ictal chunks of the same seizure (chop_master_windows
      splits one seizure into many window-sized rows) share the validity
      of the first chunk.
    * Ictals whose nearest preceding non-ictal row is ``c*``/``q*``/``x*``
      (or that have no preceding event at all) are dropped.

    FIX: the previous implementation required the *immediately* preceding
    row to be ``p*``. Because a ``p*_sopbuffer`` row (classified as
    excluded) always sits between the preictal window and the seizure, that
    condition was never satisfiable -- and since a chopped seizure's 2nd..Nth
    chunks are preceded by another ictal chunk, those failed too. Net effect:
    EVERY ictal window was silently dropped, so the seizure-type head was
    only ever trained on preictal chunks minutes before onset (where the
    type is essentially invisible) and never on the ictal EEG where seizure
    morphology actually differs by type.
    """
    keep = pd.Series(True, index=df.index)

    # TUSZ per-channel annotation CSVs carry one row PER CHANNEL per event,
    # with per-channel start/stop times that differ for focal seizures. The
    # lead-in scan must therefore run per (session, channel): grouped by
    # session alone, rows from different channels interleave in time and a
    # 'bg' chunk from channel B (whose event ended earlier) can land between
    # two ictal chunks of channel A and invalidate the rest of A's chunks.
    group_cols = ["session_key"]
    if channel_col is not None and channel_col in df.columns:
        group_cols.append(channel_col)

    for _, grp in df.groupby(group_cols, sort=False):
        grp_sorted = grp.sort_values(start_col)
        lbls = grp_sorted[label_col].astype(str).tolist()
        orig_idx = grp_sorted.index.tolist()

        last_non_ictal: Optional[str] = None   # nearest preceding non-ictal, non-sopbuffer label
        prev_was_ictal = False
        prev_ictal_valid = False
        for idx, lbl in zip(orig_idx, lbls):
            cat = classify_label(lbl)
            if cat == LABEL_CATEGORY_ICTAL:
                if prev_was_ictal:
                    valid = prev_ictal_valid          # same seizure, inherit
                else:
                    valid = (
                        last_non_ictal is not None
                        and classify_label(last_non_ictal) == LABEL_CATEGORY_PREICTAL
                    )
                keep[idx] = valid
                prev_was_ictal = True
                prev_ictal_valid = valid
            else:
                prev_was_ictal = False
                if not _is_sopbuffer_label(lbl):
                    last_non_ictal = lbl

    return keep